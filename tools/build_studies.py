#!/usr/bin/env python3
"""Validate researched Companies House case files and write app/content/studies.js.

    python3 tools/build_studies.py path/to/cases.json [more.json ...]
"""
import json, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NUM = ("revenue", "gross_profit", "operating_profit", "adj_ebitda", "pbt", "staff_costs", "headcount", "cash", "deferred_income", "capitalised_dev", "recurring_share")


def check(c):
    errs = []
    for f in ("id", "company", "number", "sector", "owner", "difficulty", "anon", "years", "context", "challenges", "wins", "risks", "decision", "analysis", "sources"):
        if f not in c:
            errs.append(f"missing {f}")
    if c.get("difficulty") not in ("easy", "medium", "hard"):
        errs.append("difficulty must be easy/medium/hard")
    ys = c.get("years", [])
    if len(ys) < 2:
        errs.append("need at least 2 years")
    for y in ys:
        for k in NUM:
            v = y.get(k)
            if v is not None and not isinstance(v, (int, float)):
                errs.append(f"{y.get('fy')} {k} not numeric")
    d = c.get("decision", {})
    if len(d.get("options", [])) < 3 or len(d.get("why", [])) != len(d.get("options", [])):
        errs.append("decision needs 3-4 options with a matching why per option")
    if not isinstance(d.get("best"), int) or not 0 <= d.get("best", -1) < len(d.get("options", [])):
        errs.append("decision.best out of range")
    if d.get("as_of") not in [y.get("fy") for y in ys]:
        errs.append("decision.as_of must match a year's fy")
    for q in c.get("analysis", []):
        if not all(k in q for k in ("q", "answer", "unit", "tol", "working")):
            errs.append("analysis item incomplete")
    if c.get("company") and c.get("anon") and c["company"].split()[0].lower() in c["anon"].lower():
        errs.append("anon alias reveals the company name")
    return errs


def main():
    cases, bad = [], 0
    for p in sys.argv[1:]:
        for c in json.loads(pathlib.Path(p).read_text()):
            e = check(c)
            if e:
                bad += 1
                print(f"REJECT {c.get('id')}: {'; '.join(e)}")
                continue
            cases.append(c)
    ids = [c["id"] for c in cases]
    assert len(ids) == len(set(ids)), "duplicate ids"
    order = {"easy": 0, "medium": 1, "hard": 2}
    cases.sort(key=lambda c: order[c["difficulty"]])
    body = json.dumps(cases, ensure_ascii=False, indent=1).replace("</", "<\\/")
    (ROOT / "app/content/studies.js").write_text("/* Real company studies built from UK Companies House filings (figures as filed, £k). Generated by tools/build_studies.py. */\nMDS.content.studies = " + body + ";\n", encoding="utf-8")
    print(f"Wrote {len(cases)} studies ({bad} rejected): " + ", ".join(f"{d}={sum(c['difficulty'] == d for c in cases)}" for d in order))


if __name__ == "__main__":
    main()
